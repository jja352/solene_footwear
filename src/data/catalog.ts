export function getProductBySlug(slug: string): Product | undefined {
  return PRODUCTS.find((p) => p.slug === slug);
}

export function getProductById(id: string): Product | undefined {
  return PRODUCTS.find((p) => p.id === id);
}

export function getEffectivePrice(product: Product): number {
  return product.discountPrice && product.discountPrice < product.price ? product.discountPrice : product.price;
}

export function getDiscountPercentage(product: Product): number {
  if (!product.discountPrice || product.discountPrice >= product.price) return 0;
  return Math.round(((product.price - product.discountPrice) / product.price) * 100);
}

export function getAllAvailableColors(products: Product[] = PRODUCTS): ProductColor[] {
  const seen = new Map<string, ProductColor>();
  products.forEach((p) => {
    p.colors.forEach((c) => {
      if (!seen.has(c.name)) seen.set(c.name, c);
    });
  });
  return Array.from(seen.values());
}

export function getAllAvailableSizes(products: Product[] = PRODUCTS): string[] {
  const seen = new Set<string>();
  products.forEach((p) => p.sizes.forEach((s) => seen.add(s)));
  return Array.from(seen).sort((a, b) => {
    const numA = parseFloat(a.replace(/[^\d.]/g, '')) || 0;
    const numB = parseFloat(b.replace(/[^\d.]/g, '')) || 0;
    return numA - numB;
  });
}

export function categoryToSlug(category: string): string {
  return category
    .toLowerCase()
    .replace(/&/g, 'and')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');
}

export function slugToCategory(slug: string, department?: 'men' | 'women'): string | undefined {
  const pool =
    department === 'men'
      ? MEN_CATEGORIES
      : department === 'women'
        ? WOMEN_CATEGORIES
        : [...MEN_CATEGORIES, ...WOMEN_CATEGORIES];
  return pool.find((cat) => categoryToSlug(cat) === slug);
}
